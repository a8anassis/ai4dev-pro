def swap(a, b):
    """Ανταλλάσσει τις τιμές των a και b."""
    return b, a     # tuple



def main():
    """Κύρια συνάρτηση για την εκτέλεση του προγράμματος."""
    a = 5
    b = 10

    print(f"Πριν την ανταλλαγή: a = {a}, b = {b}")
    # a, b = swap(a, b)
    a, b = b, a  # Ανταλλαγή τιμών χωρίς τη χρήση της συνάρτησης swap
    print(f"Μετά την ανταλλαγή: a = {a}, b = {b}")

if __name__ == "__main__":
    main()