"""Υπολογισμός αν είναι ορθογώνιο τρίγωνο σε Python."""


EPSILON = 0.000005
a = float(input("Εισάγετε την πρώτη πλευρά του τριγώνου (υποτείνουσα): "))
b = float(input("Εισάγετε τη δεύτερη πλευρά του τριγώνου: "))
c = float(input("Εισάγετε την τρίτη πλευρά του τριγώνου: "))

# Πάντα η ισότητα στους float ελέγχεται με ένα μικρό περιθώριο (EPSILON),
# όχι με το ==, λόγω της απώλειας ακρίβειας των float αριθμών.
is_right = abs(a**2 - (b**2 + c**2)) <= EPSILON

print(f"Το τρίγωνο είναι ορθογώνιο: {is_right}")